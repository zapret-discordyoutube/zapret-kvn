def farewell(succeeded: bool, *, rng: random.Random | None = None) -> str:
    """Прощальная фраза: каждый раз своя, чтобы конец обновления не приедался."""
    return (rng or random).choice(DONE if succeeded else FAILED)


class PhraseDeck:
    """Фразы в случайном порядке без повторов, пока колода не кончится."""

    def __init__(self, phrases: tuple[str, ...] = WAITING, *, rng: random.Random | None = None):
        self._phrases = phrases
        self._rng = rng or random.Random()
        self._queue: list[str] = []
        self._last = ""

    def next(self) -> str:
        if not self._queue:
            self._queue = list(self._phrases)
            self._rng.shuffle(self._queue)
            # Новая колода не начинается с фразы, которой кончилась прошлая.
            if len(self._queue) > 1 and self._queue[-1] == self._last:
                self._queue.insert(0, self._queue.pop())
        self._last = self._queue.pop()
        return self._last
