def country_title(code: str) -> str:
    """«Германия» for ``DE``; an unknown code is shown as it is, an empty one as «Страна не определена»."""
    value = str(code or "").strip().upper()
    if not value:
        return "Страна не определена"
    return _NAMES.get(value, value)
