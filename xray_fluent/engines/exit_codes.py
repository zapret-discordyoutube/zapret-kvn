"""Коды завершения процессов Windows простыми словами.

Ядро упало — в журнале и в окне остаётся число вроде ``-1073740777``, по которому человек
ничего не поймёт, а поддержка не найдёт причину. Здесь число приводится к привычному виду
(``0xC0000417``) и, если код известен, получает короткое объяснение.
"""

from __future__ import annotations

_KNOWN: dict[int, str] = {
    0xC0000005: "обращение к недоступной памяти",
    0xC0000409: "аварийная остановка по защите от переполнения буфера",
    0xC0000417: (
        "недопустимый параметр в нативной библиотеке; так падают библиотеки драйвера сетевого адаптера "
        "или WinDivert, когда рядом работает ещё один перехватчик пакетов"
    ),
    0xC000013A: "прервано сигналом Ctrl+C",
    0xC0000135: "не найдена нужная библиотека",
    0xC000007B: "библиотека другой разрядности",
    0xC0000142: "не удалось запустить библиотеку",
}


def describe_exit_code(code: int | None) -> str:
    """``0xC0000417 (объяснение)`` для кода Windows; обычные небольшие коды — числом."""

    if code is None:
        return "код неизвестен"
    unsigned = int(code) & 0xFFFFFFFF
    if unsigned < 0x10000:
        return f"код {unsigned}"
    meaning = _KNOWN.get(unsigned)
    text = f"код 0x{unsigned:08X}"
    return f"{text} ({meaning})" if meaning else text


__all__ = ["describe_exit_code"]
