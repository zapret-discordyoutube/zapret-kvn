"""Шаги обучающей экскурсии: что подсветить и что рассказать.

Шаг не хранит виджет — только то, как его найти (``target``). Страницы
создаются лениво (``DeferredPage``), поэтому искать элемент можно лишь после
того, как страница шага открыта; оверлей вызывает ``target`` заново на каждом
кадре и сам следит за прокруткой и размером окна.

Тексты описывают только то, что приложение действительно делает. Меняете
поведение (режимы, подписки, проверки серверов) — поправьте и шаг.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass

from PyQt6.QtWidgets import QWidget

TourTargets = Callable[[QWidget], list[QWidget]]


@dataclass(frozen=True, slots=True)
class TourStep:
    key: str
    title: str
    body: str
    #: Атрибут главного окна со страницей, которую нужно открыть (``nodes_page``).
    #: ``None`` — остаться на текущей.
    page: str | None = None
    #: Раздел «Маршрутизации» (ключ из ``configs_page.SECTIONS``).
    section: str | None = None
    target: TourTargets | None = None
    #: Крупная карточка по центру без подсветки — для вступления.
    hero: bool = False


def nav_item(*routes: str) -> TourTargets:
    """Пункты бокового меню по ключу маршрута (``objectName`` страницы)."""

    def resolve(window: QWidget) -> list[QWidget]:
        panel = window.navigationInterface.panel
        found: list[QWidget] = []
        for route in routes:
            item = panel.items.get(route)
            if item is None:
                continue
            widget = item.widget
            # У пункта с подпунктами («Маршрутизация») строка — itemWidget.
            found.append(getattr(widget, "itemWidget", widget))
        return found

    return resolve


def on_page(page: str, *paths: str) -> TourTargets:
    """Элементы страницы по пути из атрибутов: ``"overview.reset_btn"``.

    Звено пути может быть и ключом словаря (``"kind_rows.tcp"``).
    """

    def resolve(window: QWidget) -> list[QWidget]:
        host = getattr(window, page)
        ensure = getattr(host, "ensure_page", None)
        root = ensure() if ensure is not None else host
        found: list[QWidget] = []
        for path in paths:
            current = root
            for part in path.split("."):
                current = current.get(part) if isinstance(current, dict) else getattr(current, part, None)
                if current is None:
                    break
            if isinstance(current, QWidget):
                found.append(current)
        return found

    return resolve


