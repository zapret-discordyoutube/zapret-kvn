def help_link(parent: QWidget) -> HyperlinkButton:
    """Ссылка без рамки: акцентный текст с иконкой вопроса."""
    link = HyperlinkButton(parent)
    link.setText(LINK_LABEL)
    link.setIcon(FIF.HELP)
    link.setToolTip(LINK_TEXT)
    link.setSizePolicy(QSizePolicy.Policy.Maximum, QSizePolicy.Policy.Fixed)
    return link


class GuideDialog(MessageBoxBase):
    """Стоковое окно поверх приложения: иллюстрация раздела и текст для новичка."""

    #: Ширина окна и отступ от краёв главного окна.
    WIDTH = 680
    MARGIN = 48

    def __init__(self, key: str, parent: QWidget, feed: Callable[[ArtCanvas], None] | None = None):
        super().__init__(parent)
        title, paragraphs = GUIDES[key]
        self.key = key
        self.title_label = SubtitleLabel(title, self.widget)
        self.viewLayout.addWidget(self.title_label)
        self.art = ART_CLASSES[key](self.widget)
        if feed is not None:
            feed(self.art)
        self.viewLayout.addWidget(self.art)

        self.scroll = ScrollArea(self.widget)
        self.scroll.setWidgetResizable(True)
        self.scroll.enableTransparentBackground()
        self.scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        body = QWidget()
        body.setStyleSheet("QWidget { background: transparent; }")
        column = QVBoxLayout(body)
        column.setContentsMargins(0, 0, 12, 0)
        column.setSpacing(10)
        self.labels: list[BodyLabel] = []
        for paragraph in paragraphs:
            if isinstance(paragraph, tuple):
                label = StrongBodyLabel(paragraph[1], body)
            else:
                label = BodyLabel(paragraph, body)
            label.setWordWrap(True)
            label.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
            column.addWidget(label)
            self.labels.append(label)
        column.addStretch(1)
        self.scroll.setWidget(body)
        self.viewLayout.addWidget(self.scroll, 1)

        self.yesButton.setText("Понятно")
        self.cancelButton.hide()
        self.setClosableOnMaskClicked(True)
        self._fit(parent.window())

    def _fit(self, window: QWidget) -> None:
        """Окно не шире и не выше главного: текст прокручивается внутри."""
        width = max(360, min(self.WIDTH, window.width() - 2 * self.MARGIN))
        self.widget.setFixedWidth(width)
        # Заголовок, иллюстрация, кнопка и поля занимают около 330 px.
        self.scroll.setFixedHeight(max(160, min(520, window.height() - 2 * self.MARGIN - 330)))

    def text(self) -> str:
        return "\n".join(label.text() for label in self.labels)


def open_guide(key: str, parent: QWidget, feed: Callable[[ArtCanvas], None] | None = None) -> GuideDialog:
    """Показать объяснение без вложенного цикла событий; удалить после закрытия."""
    dialog = GuideDialog(key, parent.window(), feed)
    dialog.finished.connect(lambda _code: dispose_later(dialog))
    dialog.open()
    return dialog
